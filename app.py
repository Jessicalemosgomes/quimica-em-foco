    notas_rows = row_dicts(conn.execute("SELECT av.titulo,av.data,n.nota,av.valor,av.conteudo FROM notas n JOIN avaliacoes av ON av.id=n.avaliacao_id WHERE n.aluno_id=? ORDER BY av.data", (aluno_id,)))
