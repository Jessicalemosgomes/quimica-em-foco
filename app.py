@app.route("/")
def dashboard():
    conn = get_db()
    turma, aluno, inicio, fim = selected_filters()
    turma_id = int(turma) if turma.isdigit() else None
    aluno_id = int(aluno) if aluno.isdigit() else None

    where = ["a.ativo = 1"]
    params = []
    if turma_id:
        where.append("a.turma_id = ?"); params.append(turma_id)
    if aluno_id:
        where.append("a.id = ?"); params.append(aluno_id)

    student_count = conn.execute(f"SELECT COUNT(*) c FROM alunos a WHERE {' AND '.join(where)}", params).scalar_one()

    note_where = ["1=1"]; note_params = []
    if turma_id:
        note_where.append("a.turma_id = ?"); note_params.append(turma_id)
    if aluno_id:
        note_where.append("a.id = ?"); note_params.append(aluno_id)
    if inicio:
        note_where.append("av.data >= ?"); note_params.append(inicio)
    if fim:
        note_where.append("av.data <= ?"); note_params.append(fim)

    avg_row = row_dict(conn.execute(
        f"""SELECT AVG(n.nota) media FROM notas n
            JOIN alunos a ON a.id=n.aluno_id JOIN avaliacoes av ON av.id=n.avaliacao_id
            WHERE {' AND '.join(note_where)}""", note_params))
    average = round(avg_row["media"], 2) if avg_row["media"] is not None else 0

    eval_sql = "SELECT COUNT(*) c FROM avaliacoes av WHERE 1=1"
    eval_params = []
    if turma_id: eval_sql += " AND av.turma_id = ?"; eval_params.append(turma_id)
    if inicio: eval_sql += " AND av.data >= ?"; eval_params.append(inicio)
    if fim: eval_sql += " AND av.data <= ?"; eval_params.append(fim)
    eval_count = conn.execute(eval_sql, eval_params).scalar_one()

    freq_where = ["1=1"]; freq_params = []
    if turma_id: freq_where.append("a.turma_id = ?"); freq_params.append(turma_id)
    if aluno_id: freq_where.append("a.id = ?"); freq_params.append(aluno_id)
    if inicio: freq_where.append("f.data >= ?"); freq_params.append(inicio)
    if fim: freq_where.append("f.data <= ?"); freq_params.append(fim)
    fr = row_dict(conn.execute(
        f"""SELECT AVG(CASE WHEN f.presente=1 THEN 100.0 ELSE 0 END) pct
            FROM frequencia f JOIN alunos a ON a.id=f.aluno_id
            WHERE {' AND '.join(freq_where)}""", freq_params))
    attendance = round(fr["pct"], 1) if fr["pct"] is not None else 0

    eval_filters = []
    eval_params = []
    if turma_id: eval_filters.append("av.turma_id = ?"); eval_params.append(turma_id)
    if inicio: eval_filters.append("av.data >= ?"); eval_params.append(inicio)
    if fim: eval_filters.append("av.data <= ?"); eval_params.append(fim)
    eval_rows = row_dicts(conn.execute(
        f"""SELECT av.id, av.titulo, av.data, av.tipo, av.conteudo, ROUND(CAST(AVG(n.nota) AS NUMERIC),2) media
            FROM avaliacoes av LEFT JOIN notas n ON n.avaliacao_id=av.id
            LEFT JOIN alunos a ON a.id=n.aluno_id
            WHERE {' AND '.join(eval_filters) if eval_filters else '1=1'}
            GROUP BY av.id ORDER BY av.data""", eval_params))
    evolution = [{"label": r["titulo"], "data": r["data"], "media": r["media"] or 0} for r in eval_rows]

    distribution = {"0-4": 0, "4-6": 0, "6-8": 0, "8-10": 0}
    for row in row_dicts(conn.execute(
        f"""SELECT n.nota FROM notas n JOIN alunos a ON a.id=n.aluno_id
            JOIN avaliacoes av ON av.id=n.avaliacao_id WHERE {' AND '.join(note_where)}""", note_params)):
        n = row["nota"]
        if n < 4: distribution["0-4"] += 1
        elif n < 6: distribution["4-6"] += 1
        elif n < 8: distribution["6-8"] += 1
        else: distribution["8-10"] += 1

    student_rows = row_dicts(conn.execute(
        f"""SELECT a.id, a.nome, a.matricula, t.nome turma,
                   ROUND(CAST(AVG(n.nota) AS NUMERIC),2) media,
                   ROUND(CAST(AVG(CASE WHEN f.presente=1 THEN 100.0 ELSE 0 END) AS NUMERIC),1) frequencia
            FROM alunos a JOIN turmas t ON t.id=a.turma_id
            LEFT JOIN notas n ON n.aluno_id=a.id LEFT JOIN avaliacoes av ON av.id=n.avaliacao_id
            LEFT JOIN frequencia f ON f.aluno_id=a.id
            WHERE {' AND '.join(where)} GROUP BY a.id, a.nome, a.matricula, t.nome ORDER BY a.nome""", params))

    attention = []
    for s in student_rows:
        reasons = []
        if s["media"] is not None and s["media"] < 6: reasons.append("média abaixo de 6")
        if s["frequencia"] is not None and s["frequencia"] < 75: reasons.append("frequência abaixo de 75%")
        if reasons: attention.append({"nome": s["nome"], "turma": s["turma"], "motivos": reasons})

    alunos_turma = row_dicts(conn.execute(
        "SELECT id,nome FROM alunos WHERE ativo=1 " + ("AND turma_id=? " if turma_id else "") + "ORDER BY nome",
        (turma_id,) if turma_id else ()
    ))
    conn.close()

    return render_template("dashboard.html", student_count=student_count, average=average,
        eval_count=eval_count, attendance=attendance, evolution=evolution, distribution=distribution,
        students=student_rows, attention=attention, alunos_turma=alunos_turma,
        filtros={"turma": turma, "aluno": aluno, "inicio": inicio, "fim": fim})


