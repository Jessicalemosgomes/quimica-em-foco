class DB:
    """Pequeno adaptador para manter as consultas do projeto legíveis."""
    def __init__(self):
        self.conn = engine.connect()
        self.transaction = self.conn.begin()

    @staticmethod
    def _adapt(sql, params):
        if not params:
            return sql, {}
        params = tuple(params) if not isinstance(params, dict) else params
        if isinstance(params, dict):
            return sql, params
        parts = sql.split("?")
        if len(parts) == 1:
            return sql, params
        out = parts[0]
        bound = {}
        for i, part in enumerate(parts[1:]):
            name = f"p{i}"
            out += f":{name}" + part
            bound[name] = params[i]
        return out, bound

    def execute(self, sql, params=()):
        sql, bound = self._adapt(sql, params)
        return self.conn.execute(text(sql), bound)

    def executemany(self, sql, rows):
        rows = list(rows)
        if not rows:
            return
        adapted_sql, _ = self._adapt(sql, rows[0])
        bound_rows = []
        for row in rows:
            _, bound = self._adapt(sql, row)
            bound_rows.append(bound)
        self.conn.execute(text(adapted_sql), bound_rows)

    def executescript(self, script):
        statements = [s.strip() for s in script.split(";") if s.strip()]
        for statement in statements:
            self.execute(statement)

    def commit(self):
        self.transaction.commit()
        self.transaction = self.conn.begin()

    def close(self):
        try:
            self.transaction.commit()
        finally:
            self.conn.close()


def get_db():
    return DB()


def row_dicts(result):
    return result.mappings().all()


def row_dict(result):
    return result.mappings().first()


def init_db():
    conn = get_db()
    if engine.dialect.name == "sqlite":
        id_def = "INTEGER PRIMARY KEY AUTOINCREMENT"
    else:
        id_def = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

    conn.executescript(f"""
    CREATE TABLE IF NOT EXISTS turmas (
        id {id_def}, nome TEXT NOT NULL, ano TEXT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS alunos (
        id {id_def}, nome TEXT NOT NULL, matricula TEXT, turma_id INTEGER NOT NULL,
        ativo INTEGER NOT NULL DEFAULT 1,
        FOREIGN KEY (turma_id) REFERENCES turmas(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS avaliacoes (
        id {id_def}, titulo TEXT NOT NULL, data TEXT NOT NULL, turma_id INTEGER NOT NULL,
        conteudo TEXT, valor REAL NOT NULL DEFAULT 10, tipo TEXT NOT NULL DEFAULT 'Prova',
        FOREIGN KEY (turma_id) REFERENCES turmas(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS notas (
        id {id_def}, avaliacao_id INTEGER NOT NULL, aluno_id INTEGER NOT NULL, nota REAL NOT NULL,
        UNIQUE(avaliacao_id, aluno_id),
        FOREIGN KEY (avaliacao_id) REFERENCES avaliacoes(id) ON DELETE CASCADE,
        FOREIGN KEY (aluno_id) REFERENCES alunos(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS frequencia (
        id {id_def}, aluno_id INTEGER NOT NULL, data TEXT NOT NULL, presente INTEGER NOT NULL, observacao TEXT,
        UNIQUE(aluno_id, data),
        FOREIGN KEY (aluno_id) REFERENCES alunos(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS conteudos (
        id {id_def}, titulo TEXT NOT NULL, data TEXT NOT NULL, turma_id INTEGER NOT NULL, unidade TEXT, observacao TEXT,
        FOREIGN KEY (turma_id) REFERENCES turmas(id) ON DELETE CASCADE
    );
    """)
    conn.commit()

    if conn.execute("SELECT COUNT(*) AS c FROM turmas").scalar_one() == 0:
        seed_demo(conn)
    conn.close()


