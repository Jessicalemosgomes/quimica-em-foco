@app.route("/avaliacoes/<int:avaliacao_id>/notas", methods=["GET", "POST"])
def notas(avaliacao_id):
    conn = get_db()
    av = row_dict(conn.execute("SELECT av.*, t.nome turma FROM avaliacoes av JOIN turmas t ON t.id=av.turma_id WHERE av.id=?", (avaliacao_id,)))
    if not av: conn.close(); return "Avaliação não encontrada", 404
    alunos = row_dicts(conn.execute("""SELECT a.id,a.nome,a.matricula,n.nota
           FROM alunos a LEFT JOIN notas n ON n.aluno_id=a.id AND n.avaliacao_id=?
           WHERE a.turma_id=? AND a.ativo=1 ORDER BY a.nome""", (avaliacao_id, av["turma_id"])))
    if request.method == "POST":
        for aluno in alunos:
            value = request.form.get(f"nota_{aluno['id']}", "").strip()
            if value != "":
                try:
                    nota = max(0, min(float(av["valor"]), float(value.replace(",", "."))))
                    conn.execute("""INSERT INTO notas(avaliacao_id,aluno_id,nota) VALUES (?,?,?)
                           ON CONFLICT(avaliacao_id,aluno_id) DO UPDATE SET nota=excluded.nota""", (avaliacao_id, aluno["id"], nota))
                except ValueError: pass
        conn.commit(); flash("Notas salvas.", "success"); return redirect(url_for("notas", avaliacao_id=avaliacao_id))
    conn.close(); return render_template("notas.html", avaliacao=av, alunos=alunos)


@app.route("/frequencia", methods=["GET", "POST"])
def frequencia():
    conn = get_db(); turma = request.args.get("turma", ""); turma_id = int(turma) if turma.isdigit() else None
    data = request.args.get("data") or date.today().isoformat()
    if request.method == "POST":
        turma_id = int(request.form["turma_id"]); data = request.form["data"]
        for key, value in request.form.items():
            if key.startswith("presenca_"):
                aluno_id = int(key.split("_")[1]); presente = 1 if value == "1" else 0; obs = request.form.get(f"obs_{aluno_id}", "")
                conn.execute("""INSERT INTO frequencia(aluno_id,data,presente,observacao) VALUES (?,?,?,?)
                    ON CONFLICT(aluno_id,data) DO UPDATE SET presente=excluded.presente, observacao=excluded.observacao""", (aluno_id, data, presente, obs))
        conn.commit(); flash("Frequência registrada.", "success")
    alunos = row_dicts(conn.execute("""SELECT a.*, f.presente, f.observacao FROM alunos a
           LEFT JOIN frequencia f ON f.aluno_id=a.id AND f.data=? WHERE a.ativo=1 """ + ("AND a.turma_id=? " if turma_id else "") + "ORDER BY a.nome",
        (data, turma_id) if turma_id else (data,)))
    conn.close(); return render_template("frequencia.html", alunos=alunos, turma_id=turma_id, data=data)


