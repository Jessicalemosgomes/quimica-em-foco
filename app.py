@app.route("/api/alunos/<int:aluno_id>")
def api_aluno(aluno_id):
    conn = get_db()
    student = row_dict(conn.execute("SELECT a.*,t.nome turma FROM alunos a JOIN turmas t ON t.id=a.turma_id WHERE a.id=?", (aluno_id,)))
